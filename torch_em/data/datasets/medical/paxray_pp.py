"""The PAXRay++ dataset contains annotations for fine-grained thoracic anatomy segmentation in
2D chest radiographs.

The dataset consists of 14,753 frontal and lateral projections (512x512, generated by projecting
pseudo-labeled thorax CT scans onto a 2D plane) from 7,377 patients, each ('<case>_frontal.png' or
'<case>_lateral.png') paired with a boolean multi-channel label volume of shape (159, 512, 512)
('labels/<case>_<view>.npy'), one channel per anatomical class. Of the 159 classes, 51 are 'direct'
(directly annotated structures) and 108 are 'derived' (hierarchical unions of the direct structures,
e.g. 'spine' is the union of 'cervical spine', 'thoracic spine' and 'lumbar spine', which are
themselves unions of individual vertebrae). `get_paxray_pp_data` merges only the 51 'direct' classes
into a single semantic label image per case, where the label id of a structure is its 1-based rank among
the 'direct' channels in the order given by `paxray_label_dictionary.json`; the 'derived' classes are
redundant with (and would overlap) the 'direct' ones and are not used by this loader.

The data is located at https://doi.org/10.5281/zenodo.20688438, released under a CC-BY-NC-4.0 license.

This dataset is from the publication https://doi.org/10.48550/arXiv.2306.03934.
Please cite it if you use this dataset for your research.
"""

import os
import json
from glob import glob
from natsort import natsorted
from typing import Union, Tuple, List

import numpy as np
from tqdm import tqdm
from concurrent import futures

from torch.utils.data import Dataset, DataLoader

import torch_em

from .. import util


URLS = {
    "images": "https://zenodo.org/records/20688438/files/paxray_images.tar.gz",
    "labels": "https://zenodo.org/records/20688438/files/paxray_labels.zip",
    "label_dictionary": "https://zenodo.org/records/20688438/files/paxray_label_dictionary.json",
    "label_types": "https://zenodo.org/records/20688438/files/paxray_label_types.json",
}

CHECKSUMS = {
    "images": "e91a9d4d27b5bbfbd24046c897b7facf5391ab934936559fd75b1c92e988b99f",
    "labels": "9dc4623db0be9793be781699af0605f26a764ab5088efffbb9395adc0e2082c1",
    "label_dictionary": "f5bf6f48117f18e9cfbc2f844ad7369d043926e32fc4eeae1638b36b05da39a1",
    "label_types": "465282f18b246a9b8631a145cf7a8d4ccdc4841acea2cc7eb3eedaa4ce633768",
}


def _class_names(path):
    with open(os.path.join(path, "paxray_label_dictionary.json")) as f:
        names_by_id = json.load(f)
    with open(os.path.join(path, "paxray_label_types.json")) as f:
        types_by_id = json.load(f)

    direct_ids = sorted((int(i) for i in names_by_id if types_by_id[i] == "direct"))
    return [names_by_id[str(i)] for i in direct_ids], direct_ids


def _merge_labels(npy_path, out_path, direct_ids):
    if os.path.exists(out_path):
        return out_path

    import tifffile

    channels = np.load(npy_path)
    label = np.zeros(channels.shape[1:], dtype="uint8")
    for class_id, channel_id in enumerate(direct_ids, start=1):
        label[channels[channel_id]] = class_id

    tmp_path = f"{out_path}.incomplete.tif"
    tifffile.imwrite(tmp_path, label)
    os.replace(tmp_path, out_path)
    return out_path


def get_paxray_pp_data(path: Union[os.PathLike, str], download: bool = False) -> str:
    """Download the PAXRay++ dataset and merge the per-class label channels into semantic labels.

    Args:
        path: Filepath to a folder where the data is downloaded for further processing.
        download: Whether to download the data if it is not present.

    Returns:
        Filepath where the data is downloaded.
    """
    image_dir = os.path.join(path, "images", "paxray_images_unfiltered")
    raw_labels_dir = os.path.join(path, "labels", "labels")
    semantic_labels_dir = os.path.join(path, "semantic_labels")

    os.makedirs(path, exist_ok=True)

    for name in ("label_dictionary", "label_types"):
        util.download_source(
            path=os.path.join(path, f"paxray_{name}.json"), url=URLS[name], download=download,
            checksum=CHECKSUMS[name],
        )
    _, direct_ids = _class_names(path)

    if not os.path.exists(image_dir):
        image_tar = os.path.join(path, "images.tar.gz")
        util.download_source(path=image_tar, url=URLS["images"], download=download, checksum=CHECKSUMS["images"])
        util.unzip_tarfile(tar_path=image_tar, dst=os.path.join(path, "images"))

    if not os.path.exists(raw_labels_dir):
        label_zip = os.path.join(path, "labels.zip")
        util.download_source(path=label_zip, url=URLS["labels"], download=download, checksum=CHECKSUMS["labels"])
        util.unzip(zip_path=label_zip, dst=os.path.join(path, "labels"))

    npy_paths = natsorted(glob(os.path.join(raw_labels_dir, "*.npy")))
    if npy_paths and not all(
        os.path.exists(os.path.join(semantic_labels_dir, f"{os.path.basename(p)[:-4]}.tif")) for p in npy_paths
    ):
        os.makedirs(semantic_labels_dir, exist_ok=True)
        n_workers = min(16, os.cpu_count() or 1)
        with futures.ProcessPoolExecutor(n_workers) as pool:
            tasks = [
                pool.submit(
                    _merge_labels, p, os.path.join(semantic_labels_dir, f"{os.path.basename(p)[:-4]}.tif"),
                    direct_ids,
                ) for p in npy_paths
            ]
            for task in tqdm(futures.as_completed(tasks), total=len(tasks), desc="Merge the PAXRay++ labels"):
                task.result()

    return path


def get_paxray_pp_paths(path: Union[os.PathLike, str], download: bool = False) -> Tuple[List[str], List[str]]:
    """Get paths to the PAXRay++ data.

    Args:
        path: Filepath to a folder where the data is downloaded for further processing.
        download: Whether to download the data if it is not present.

    Returns:
        List of filepaths for the image data.
        List of filepaths for the label data.
    """
    data_dir = get_paxray_pp_data(path, download)

    label_paths = natsorted(glob(os.path.join(data_dir, "semantic_labels", "*.tif")))
    raw_paths = [
        os.path.join(data_dir, "images", "paxray_images_unfiltered", f"{os.path.basename(p)[:-4]}.png")
        for p in label_paths
    ]

    assert len(raw_paths) == len(label_paths) and len(raw_paths) > 0
    assert all(os.path.exists(p) for p in raw_paths)

    return raw_paths, label_paths


def get_paxray_pp_dataset(
    path: Union[os.PathLike, str],
    patch_shape: Tuple[int, int],
    resize_inputs: bool = False,
    download: bool = False,
    **kwargs
) -> Dataset:
    """Get the PAXRay++ dataset for thoracic anatomy segmentation in chest radiographs.

    Args:
        path: Filepath to a folder where the data is downloaded for further processing.
        patch_shape: The patch shape to use for training.
        resize_inputs: Whether to resize the inputs to the patch shape.
        download: Whether to download the data if it is not present.
        kwargs: Additional keyword arguments for `torch_em.default_segmentation_dataset`.

    Returns:
        The segmentation dataset.
    """
    raw_paths, label_paths = get_paxray_pp_paths(path, download)

    if resize_inputs:
        resize_kwargs = {"patch_shape": patch_shape, "is_rgb": True}
        kwargs, patch_shape = util.update_kwargs_for_resize_trafo(
            kwargs=kwargs, patch_shape=patch_shape, resize_inputs=resize_inputs, resize_kwargs=resize_kwargs
        )

    return torch_em.default_segmentation_dataset(
        raw_paths=raw_paths,
        raw_key=None,
        label_paths=label_paths,
        label_key=None,
        patch_shape=patch_shape,
        is_seg_dataset=False,
        **kwargs
    )


def get_paxray_pp_loader(
    path: Union[os.PathLike, str],
    batch_size: int,
    patch_shape: Tuple[int, int],
    resize_inputs: bool = False,
    download: bool = False,
    **kwargs
) -> DataLoader:
    """Get the PAXRay++ dataloader for thoracic anatomy segmentation in chest radiographs.

    Args:
        path: Filepath to a folder where the data is downloaded for further processing.
        batch_size: The batch size for training.
        patch_shape: The patch shape to use for training.
        resize_inputs: Whether to resize the inputs to the patch shape.
        download: Whether to download the data if it is not present.
        kwargs: Additional keyword arguments for `torch_em.default_segmentation_dataset` or for the PyTorch DataLoader.

    Returns:
        The DataLoader.
    """
    ds_kwargs, loader_kwargs = util.split_kwargs(torch_em.default_segmentation_dataset, **kwargs)
    dataset = get_paxray_pp_dataset(path, patch_shape, resize_inputs, download, **ds_kwargs)
    return torch_em.get_data_loader(dataset, batch_size, **loader_kwargs)
