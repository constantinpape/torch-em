"""The BOBs (Baby Open Brains) dataset contains manually curated and expert-reviewed brain
segmentations for infant MRI.

The dataset consists of 71 longitudinal imaging visits from 51 children aged 1-9 months, part
of the UNC/UMN Baby Connectome Project. Each visit has paired T1-weighted and T2-weighted MRI
scans, together with a semantic segmentation of the cerebral tissues and 23 subcortical
structures (FreeSurfer-style label ids). The segmentations were initially generated by the
BIBSNet deep learning pipeline and subsequently manually corrected by trained specialists.

NOTE: This module uses the T2-weighted scans by default (`modality="T2w"`), the primary
modality for the infant-abcd-bids-pipeline / BIBSNet segmentation protocol. The complete label
lookup table (id, RGB color, name) is shipped with the data in 'dseg.tsv', which is downloaded
next to the volumes.

The dataset is located at https://bobsrepository.readthedocs.io/ (hosted as a public AWS S3
bucket, and archived on OSF at https://doi.org/10.17605/OSF.IO/WDR78) and is distributed under
the CC BY 4.0 license.

This dataset is from the publication https://doi.org/10.1038/s41597-025-05404-y.
Please cite it if you use this dataset in your research.
"""

import os
from glob import glob
from natsort import natsorted
from typing import Union, Tuple, Literal, List

from torch.utils.data import Dataset, DataLoader

import torch_em

from .. import util


BASE_URL = "https://bobsrepository.s3.us-east-2.amazonaws.com"
ARCHIVE_URL = f"{BASE_URL}/V1.0.zip"
DSEG_URL = f"{BASE_URL}/dseg.tsv"


def get_bobs_data(path: Union[os.PathLike, str], download: bool = False) -> str:
    """Download the BOBs dataset.

    Args:
        path: Filepath to a folder where the data is downloaded for further processing.
        download: Whether to download the data if it is not present.

    Returns:
        Filepath where the data is downloaded.
    """
    data_dir = os.path.join(path, "data")
    if os.path.exists(data_dir):
        return data_dir

    os.makedirs(path, exist_ok=True)

    zip_path = os.path.join(path, "V1.0.zip")
    util.download_source(path=zip_path, url=ARCHIVE_URL, download=download, checksum=None)
    util.unzip(zip_path=zip_path, dst=data_dir)

    dseg_path = os.path.join(path, "dseg.tsv")
    util.download_source(path=dseg_path, url=DSEG_URL, download=download, checksum=None)

    return data_dir


def get_bobs_paths(
    path: Union[os.PathLike, str], modality: Literal["T1w", "T2w"] = "T2w", download: bool = False
) -> Tuple[List[str], List[str]]:
    """Get paths to the BOBs data.

    Args:
        path: Filepath to a folder where the data is downloaded for further processing.
        modality: The MRI modality. Either 'T1w' or 'T2w'.
        download: Whether to download the data if it is not present.

    Returns:
        List of filepaths for the image data.
        List of filepaths for the label data.
    """
    if modality not in ("T1w", "T2w"):
        raise ValueError(f"'{modality}' is not a valid modality. Choose either 'T1w' or 'T2w'.")

    data_dir = get_bobs_data(path, download)

    label_paths = natsorted(glob(os.path.join(data_dir, "sub-*", "ses-*", "anat", "*_desc-aseg_dseg.nii.gz")))
    raw_paths = [p.replace("_desc-aseg_dseg.nii.gz", f"_{modality}.nii.gz") for p in label_paths]

    keep = [i for i, p in enumerate(raw_paths) if os.path.exists(p)]
    raw_paths = [raw_paths[i] for i in keep]
    label_paths = [label_paths[i] for i in keep]

    assert len(raw_paths) == len(label_paths) and len(raw_paths) > 0

    return raw_paths, label_paths


def get_bobs_dataset(
    path: Union[os.PathLike, str],
    patch_shape: Tuple[int, ...],
    modality: Literal["T1w", "T2w"] = "T2w",
    resize_inputs: bool = False,
    download: bool = False,
    **kwargs
) -> Dataset:
    """Get the BOBs dataset for infant brain tissue and subcortical structure segmentation.

    Args:
        path: Filepath to a folder where the data is downloaded for further processing.
        patch_shape: The patch shape to use for training.
        modality: The MRI modality. Either 'T1w' or 'T2w'.
        resize_inputs: Whether to resize inputs to the desired patch shape.
        download: Whether to download the data if it is not present.
        kwargs: Additional keyword arguments for `torch_em.default_segmentation_dataset`.

    Returns:
        The segmentation dataset.
    """
    raw_paths, label_paths = get_bobs_paths(path, modality, download)

    if resize_inputs:
        resize_kwargs = {"patch_shape": patch_shape, "is_rgb": False}
        kwargs, patch_shape = util.update_kwargs_for_resize_trafo(
            kwargs=kwargs, patch_shape=patch_shape, resize_inputs=resize_inputs, resize_kwargs=resize_kwargs
        )

    return torch_em.default_segmentation_dataset(
        raw_paths=raw_paths,
        raw_key="data",
        label_paths=label_paths,
        label_key="data",
        patch_shape=patch_shape,
        is_seg_dataset=True,
        **kwargs
    )


def get_bobs_loader(
    path: Union[os.PathLike, str],
    batch_size: int,
    patch_shape: Tuple[int, ...],
    modality: Literal["T1w", "T2w"] = "T2w",
    resize_inputs: bool = False,
    download: bool = False,
    **kwargs
) -> DataLoader:
    """Get the BOBs dataloader for infant brain tissue and subcortical structure segmentation.

    Args:
        path: Filepath to a folder where the data is downloaded for further processing.
        batch_size: The batch size for training.
        patch_shape: The patch shape to use for training.
        modality: The MRI modality. Either 'T1w' or 'T2w'.
        resize_inputs: Whether to resize inputs to the desired patch shape.
        download: Whether to download the data if it is not present.
        kwargs: Additional keyword arguments for `torch_em.default_segmentation_dataset` or for the PyTorch DataLoader.

    Returns:
        The DataLoader.
    """
    ds_kwargs, loader_kwargs = util.split_kwargs(torch_em.default_segmentation_dataset, **kwargs)
    dataset = get_bobs_dataset(path, patch_shape, modality, resize_inputs, download, **ds_kwargs)
    return torch_em.get_data_loader(dataset, batch_size, **loader_kwargs)
